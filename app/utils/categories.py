def determine_category(text: str) -> str:
    t = text.lower()
    if any(
        k in t
        for k in [
            "о полиции",
            "закон",
            "норматив",
            "карточка заместитель",
            "комнат",
            "хранени",
            "кхо",
            "огневой подготовк",
            "рубеж",
            "мишен",
            "наушник",
            "очки",
            "упражнени",
            "боевого питания",
            "закрепление",
            "выдача",
            "в отношении каких лиц",
            "запрет на применение",
            "безопасност",
            "запрещает",
            "разрешает",
        ]
    ):
        return "Правовые основы и нормативы"

    if any(
        k in t
        for k in [
            "макаров",
            "пм ",
            "пм,",
            "пм.",
            "пм:",
            "пистолет макарова",
            "9-мм пистолет",
            "пистолета",
        ]
    ):
        return "Пистолет Макарова (ПМ)"

    if any(
        k in t
        for k in [
            "калашников",
            "ак-74",
            "ак74",
            "акм",
            "автомат калашникова",
            "автомата калашникова",
            "5,45-мм",
            "5.45-мм",
            "автомата",
        ]
    ):
        return "Автомат Калашникова (АК)"

    if any(
        k in t
        for k in [
            "баллистик",
            "траектор",
            "период",
            "выстрел",
            "полет",
            "скорост",
            "деривац",
            "прицел",
            "рассеиван",
            "тысячн",
            "деление прицела",
            "прямого выстрела",
            "плоскость стрельбы",
            "дальность",
            "линия возвышения",
            "точка встречи",
            "угол наибольшей",
            "настильн",
            "линия прицеливания",
        ]
    ):
        return "Основы стрельбы и баллистика"

    return "Боеприпасы и устройство оружия"
